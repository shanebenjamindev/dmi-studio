const SCENE_SCHEMA = {
  type: 'object',
  properties: {
    layout: { type: 'string', enum: ['title', 'bullets', 'stat', 'quote', 'split', 'outro'] },
    headline: { type: 'string', description: 'Main on-screen text. Short and punchy (max ~8 words).' },
    subtext: { type: 'string', description: 'Secondary line (max ~14 words). Attribution for quotes, button label for outro.' },
    bullets: { type: 'array', items: { type: 'string' }, description: 'For layout=bullets: 2-4 short items (max ~6 words each).' },
    stat_value: { type: 'string', description: 'For layout=stat: number with optional prefix/suffix, e.g. "87%", "$2.4M", "10x".' },
    stat_label: { type: 'string' },
    icon: { type: 'string', description: 'One emoji representing the scene.' },
    caption: { type: 'string', description: 'Voice-over sentence for this scene, natural spoken language. Also used as subtitles.' },
    visual_prompt: { type: 'string', description: 'ENGLISH prompt for an AI video/image model to generate this scene background: subject, setting, lighting, camera movement, mood. No on-screen text, no logos, no real people by name.' },
    duration: { type: 'number', description: 'Seconds, 2.5 to 10.' },
    animation: { type: 'string', enum: ['fade', 'slide-up', 'zoom', 'typewriter', 'pop'] },
    background: { type: 'string', enum: ['gradient', 'particles', 'grid', 'waves', 'blobs', 'solid'] },
  },
  required: ['layout', 'headline', 'caption', 'visual_prompt', 'duration', 'animation', 'background', 'icon'],
};

export const STORYBOARD_SCHEMA = {
  type: 'object',
  properties: {
    title: { type: 'string' },
    palette: {
      type: 'object',
      description: 'Hex colors. bg1/bg2 = background gradient stops; strong contrast with text.',
      properties: { bg1: { type: 'string' }, bg2: { type: 'string' }, accent: { type: 'string' }, text: { type: 'string' } },
      required: ['bg1', 'bg2', 'accent', 'text'],
    },
    font: { type: 'string', enum: ['brand', 'sans', 'serif', 'mono', 'display'] },
    music: {
      type: 'object',
      properties: { mood: { type: 'string', enum: ['calm', 'upbeat', 'epic', 'none'] }, bpm: { type: 'number' } },
      required: ['mood', 'bpm'],
    },
    voice_style: { type: 'string', description: 'One sentence describing how the narrator should sound (for text-to-speech).' },
    scenes: { type: 'array', items: SCENE_SCHEMA, minItems: 2 },
  },
  required: ['title', 'palette', 'font', 'music', 'scenes'],
};

export const SYSTEM = `You are the creative director inside DMI Workspace, a tool that turns a short brief into a motion-graphics video. Text, layouts and animations are rendered on an HTML canvas; scene backgrounds can optionally be generated by AI video/image models from your visual_prompt.
Rules:
- Write ALL on-screen text and captions in the language of the user's brief (Vietnamese brief → Vietnamese video) unless told otherwise. visual_prompt is always English.
- Structure: a hook first (title layout), a body that varies layouts (bullets, stat, quote, split), and an outro with a call-to-action.
- Keep on-screen text short; put the fuller sentence in "caption" (it becomes voice-over and subtitles, ~2.5 words per second of scene).
- Choose a cohesive palette with readable contrast. Vary backgrounds and animations between scenes, tastefully.
- The sum of scene durations must match the requested length (±10%).
- Never present invented precise statistics as real facts; use user-provided numbers or label them as illustrative in the caption.
Always answer with the complete storyboard in the required JSON structure.`;

export const BRAND_GUIDE = `BRAND KIT — Detailers Movement (tagline: "Owned by you, driven by us"). Follow strictly:
- font: "brand".
- palette: use exactly one of these: ${Object.entries(BRAND_PALETTES).map(([k, v]) => `${k} ${JSON.stringify(v)}`).join('; ')}. Prefer "night" or "blue" unless the brief suggests a light look.
- Voice & tone: confident, energetic, community-first; address the audience as owners/members of the movement. Short, active sentences.
- The brand logo is overlaid automatically (small mark on every scene, full logo on the outro). Do not use the brand name as an emoji or write it as a scene headline unless asked.
- Final scene: layout "outro" with a clear call-to-action; subtext is the button label (2-3 words).
- visual_prompt: premium, clean, high-contrast look with deep-blue and cyan light accents; when the topic is about vehicles/detailing, show glossy paint, reflections, foam, microfiber, close-up craftsmanship.`;

export function generatePrompt(o: { prompt: string; seconds?: number; aspect?: string; style?: string; brand?: boolean }) {
  return [
    `Brief: ${o.prompt}`,
    `Target length: about ${o.seconds || 30} seconds.`,
    `Aspect ratio: ${o.aspect || '16:9'}${o.aspect === '9:16' ? ' (vertical — keep headlines very short)' : ''}.`,
    o.style ? `Visual style: ${o.style}.` : '',
    o.brand ? '\n' + BRAND_GUIDE : '',
  ].filter(Boolean).join('\n');
}

export function refinePrompt(o: { storyboard: any; instruction: string; brand?: boolean }) {
  const slim = { ...o.storyboard, scenes: (o.storyboard.scenes || []).map(({ media, voice, ...s }: any) => s) };
  return `Current storyboard JSON:\n${JSON.stringify(slim)}\n\nApply this edit request and return the FULL updated storyboard. Keep every scene "id" for scenes you keep; omit "id" for new scenes. Leave everything not mentioned unchanged.\nEdit request: ${o.instruction}${o.brand ? '\n\n' + BRAND_GUIDE : ''}`;
}

// Ensure ids & defaults; carry over generated media/voice for scenes that survived a refine.
export function normalizeStoryboard(sb: any, previous?: any) {
  const prev = new Map<string, any>((previous?.scenes || []).map((s: any) => [s.id, s]));
  const out = { ...sb };
  out.title = String(out.title || 'Video mới');
  out.font = out.font || 'brand';
  out.music = { mood: 'calm', bpm: 96, ...(out.music || {}) };
  out.palette = { ...BRAND_PALETTES.night, ...(out.palette || {}) };
  out.scenes = (out.scenes || []).map((s: any) => {
    const id = s.id && prev.has(s.id) ? s.id : s.id || uid('s_');
    const old = prev.get(id);
    const scene = {
      layout: 'title', headline: '', subtext: '', bullets: [], icon: '', caption: '', visual_prompt: '',
      animation: 'fade', background: 'gradient', ...s, id,
      duration: Math.min(out.mode === 'edit' ? 3600 : 15, Math.max(1, Number(s.duration) || 4)),
    };
    // Carry over generated assets unless the client explicitly cleared them (null) or changed the source text.
    if (old?.media && scene.media === undefined && old.visual_prompt === scene.visual_prompt) scene.media = old.media;
    if (old?.voice && scene.voice === undefined && old.caption === scene.caption) scene.voice = old.voice;
    return scene;
  });
  return out;
}
